#!/usr/bin/env python3
"""Render STORY.md and strings.json from data.json, so neither can drift.

    py lesson-template/build/rpg/loch-ness-loop-rpg/render-story.py

STORY.md is the readable script — the thing Innes reads and the thing ChatGPT
is handed beside data.json. It is GENERATED from data.json (the assembled,
key-dealt text) and never edited by hand: the Kraken saga kept its script
and its data in two places and a late revision left glosses describing a
draft nobody shipped. Here the JSON is the truth and this file is its view.

strings.json is every learner-facing English string the lesson has to gloss,
one per line, answer options excluded (they are the English being taught;
rpg/README.md §1, HOUSE-STYLE §8), plus the builder's chrome strings from
meta.chrome. It is what the nine translations/<lang>.json files are keyed by,
and what check_translations.py measures them against.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = json.load(open(os.path.join(HERE, 'data.json'), encoding='utf-8'))

ORDER = ['shop1', 'shop2', 'shop3', 'shop4', 'shop5', 'shop6', 'dores',
         'shore1', 'shore2', 'shore3', 'shore4', 'hill1', 'hill2', 'hill3', 'hill4',
         'pub1', 'pub2', 'pub3', 'pier',
         'deep1', 'deep2', 'deep3', 'bay1', 'bay2', 'bay3',
         'back1', 'back2']
HEADS = {
    'shop1': '# CHAPTER 1 — THE SHOP (Inverness, Wednesday morning)',
    'dores': '# ROUTE CHOICE 1 — DORES',
    'shore1': '## The SHORE ROAD branch',
    'hill1': '## The HIGH ROAD branch',
    'pub1': '# CHAPTER 3 — FORT AUGUSTUS (Wednesday evening)',
    'pier': '# ROUTE CHOICE 2 — THE PIER (Thursday, six in the morning)',
    'deep1': '## The CASTLE branch',
    'bay1': '## The BAY branch',
    'back1': '# CHAPTER 5 — THE NORTH SIDE (Thursday)',
}
PHOTO = {'shop3': 1, 'pub2': 2, 'deep3': 3, 'bay3': 3, 'back1': 4}


def wc(s):
    return len(s.split())


def scene_md(sid, n, s):
    out = []
    kind = s.get('kind', '')
    out.append('### %d. %s  [%s]' % (n, s['title'], kind))
    out.append('**Act:** %s · **Picture:** `%s` · **Object:** %s' % (s['act'], s['image'], s['hotspot']['object']))
    out.append('')
    out.append('**Story.** %s' % s['story'])
    out.append('')
    out.append('**Clue.** %s' % s['clue'])
    out.append('')
    out.append('**%s**' % s['prompt'])
    out.append('')
    for i, a in enumerate(s['answers']):
        out.append('- %s) %s%s' % ('ABC'[i], a['text'], '  ✔' if a.get('correct') else ''))
    out.append('')
    out.append('**Why:** %s' % s['explanation'])
    if s.get('relic'):
        out.append('')
        out.append('**Right:** +5 and PHOTO %d/4. **Wrong:** −1 chance, no photo.' % PHOTO[sid])
    else:
        out.append('')
        out.append('**Right:** +5. **Wrong:** −1 chance.')
    out.append('')
    out.append('*(story %d · clue %d · prompt %d · explanation %d words; next: `%s`)*'
               % (wc(s['story']), wc(s['clue']), wc(s['prompt']), wc(s['explanation']), s['correctNext']))
    out.append('')
    out.append('---')
    out.append('')
    return '\n'.join(out)


def choice_md(sid, s):
    out = ['### %s' % s['title'],
           '**Act:** %s · **Picture:** `%s` · **Object:** %s' % (s['act'], s['image'], s['hotspot']['object']),
           '', s['story'], '']
    for c in s['choices']:
        out.append('- **%s** — button *%s* — %s → `%s`' % (c['route'], c['label'], c['note'], c['next']))
    out += ['', '---', '']
    return '\n'.join(out)


def main():
    m, cov, br = DATA['meta'], DATA['cover'], DATA['briefing']
    sc = m['scoring']
    L = []
    L.append('# %s — the script' % m['title'])
    L.append('')
    L.append('<!-- GENERATED by render-story.py from data.json. Edit script.json, run '
             'assemble-script.py, then this. Do not edit this file. -->')
    L.append('')
    L.append('A Block Camp RPG for **%s** learners: **%s**, in a world of **%s**. '
             'Two kinds of question — **[VOCAB]**, a bike part or bike verb in a line of '
             'dialogue, and **[CCQ]**, a concept check on what somebody just said. '
             'Level, cast, rules and the reasons behind them are in `BIBLE.md`; the pictures are '
             'in `IMAGES.md`; this file is the words, in play order, with the key marked ✔ in the '
             'slot it actually sits in.' % (m['level'], m['grammar'], m['world']))
    L.append('')
    L.append('## How this file is used')
    L.append('')
    L.append('- **ChatGPT** gets this file, `IMAGES.md` and `data.json`, and the standing brief '
             '`docs/CHATGPT-RPG-BRIEF.md`. Its job is the pictures, the hotspot boxes and the '
             'export file: paste `data.json` in as `window.LOCHNESS_GAME_DATA` unchanged, add '
             '`images` and each scene\'s `hotspot` box, and change no text. **Do not write '
             '`local` blocks** — the nine glosses already exist in `translations/` and the '
             'builder applies them.')
    L.append('- **The Claude session that builds it** follows `docs/HANDOFF-rpg.md`, with '
             '`img_w: 1536, img_h: 864` in the spec because the plates are 16:9.')
    L.append('')
    L.append('## Scoring')
    L.append('')
    L.append('| | |')
    L.append('|---|---|')
    L.append('| Points | +%d a correct answer |' % sc['points'])
    L.append('| Chances | %d. A wrong answer costs one; at 0 the game ends in `failed` |' % sc['chances'])
    L.append('| Photos | %d, one at each of four named scenes. Miss one and the best ending is `missing` |' % sc['tiles'])
    L.append('| Per path | %d questions, max %d, pass %d |' % (m['questionsPerPath'], sc['max'], sc['pass']))
    L.append('')
    L.append('Chrome the builder adds, glossed like everything else: HUD **%s**, relic line **%s**, '
             'PLAY AGAIN **%s**, briefing kicker **%s**.'
             % (m['chrome']['tiles'], m['chrome']['relic'], m['chrome']['restart'], m['chrome']['briefingKicker']))
    L.append('')
    L.append('---')
    L.append('')
    L.append('# COVER')
    L.append('')
    L.append('**Picture:** `%s` · **Object:** %s' % (cov['image'], cov['hotspot']['object']))
    L.append('')
    L.append('**Eyebrow:** %s  ' % cov['eyebrow'])
    L.append('**Title:** %s  ' % cov['title'])
    L.append('**Lead (%d words):** %s  ' % (wc(cov['lead']), cov['lead']))
    L.append('**Chips:** %s  ' % ' · '.join('`%s`' % r for r in cov['rules']))
    L.append('**Start button:** %s  ' % cov['start'])
    L.append('**Small line:** %s' % cov['small'])
    L.append('')
    L.append('# BRIEFING')
    L.append('')
    L.append('**Picture:** `%s` (reused) · **Title:** %s' % (br['image'], br['title']))
    L.append('')
    for i, c in enumerate(br['cards'], 1):
        L.append('%d. **%s** — %s' % (i, c['head'], c['text']))
    L.append('')
    L.append('**Note:** %s  ' % br['note'])
    L.append('**Button:** %s' % br['button'])
    L.append('')
    L.append('---')
    L.append('')
    n = 0
    for sid in ORDER:
        s = DATA['scenes'][sid]
        if sid in HEADS:
            L.append(HEADS[sid])
            L.append('')
        if 'choices' in s:
            L.append(choice_md(sid, s))
        else:
            n += 1
            L.append(scene_md(sid, n, s))
    L.append('# ENDINGS')
    L.append('')
    for key in ('master', 'complete', 'missing', 'failed'):
        e = DATA['endings'][key]
        L.append('### `%s` — %s · %s' % (key, e['label'], e['title']))
        L.append('**Picture:** `%s` · **Object:** %s' % (e['image'], e['hotspot']['object']))
        L.append('')
        L.append('%s' % e['text'])
        L.append('')
        L.append('*(%d words)*' % wc(e['text']))
        L.append('')
    with open(os.path.join(HERE, 'STORY.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L).rstrip() + '\n')

    # ── strings.json: everything a learner reads in English, options excluded
    found, seen = [], set()

    def add(v):
        v = (v or '').strip()
        if v and v not in seen:
            seen.add(v)
            found.append(v)

    for k in ('eyebrow', 'title', 'lead', 'start', 'small'):
        add(cov[k])
    for r in cov['rules']:
        add(r)
    for k in ('title', 'note', 'button'):
        add(br[k])
    for c in br['cards']:
        add(c['head']); add(c['text'])
    for sid in ORDER:
        s = DATA['scenes'][sid]
        for k in ('act', 'title', 'story', 'clue', 'prompt', 'explanation'):
            if k in s:
                add(s[k])
        for c in s.get('choices', []):
            add(c['route']); add(c['label']); add(c['note'])
    for key in ('master', 'complete', 'missing', 'failed'):
        e = DATA['endings'][key]
        for k in ('label', 'title', 'text'):
            add(e[k])
    for v in m['chrome'].values():
        add(v)
    with open(os.path.join(HERE, 'strings.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(found, f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('STORY.md: %d question scenes, %d strings to gloss -> strings.json' % (n, len(found)))


if __name__ == '__main__':
    main()
