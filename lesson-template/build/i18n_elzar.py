def render(code):
    d = dict(T[code])
    for k in LIFT:
        d[k] = CHROME[code][k]
    parts = []
    for k in sorted(d):
        parts.append('    %s: %s' % (k, d[k] if k in LIFT else json.dumps(d[k], ensure_ascii=False)))
    return '{\n' + ',\n'.join(parts) + '\n  }'


