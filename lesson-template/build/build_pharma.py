# ── activation ─────────────────────────────────────────────────────────
# The chips are the lesson's own language, so the speaking task cannot be
# completed in B1 English. Four stall moves, three record verbs, two frames.
# Eleven of these overflowed the activation slide by 8px; the two dropped
# are the ones the speaking prompts already force anyway.
CHIPS = ['I inherited', 'I owned', 'took it from &hellip; to &hellip;',
         'exceeded plan by', 'there are two parts to that',
         'let me think about that', 'could you rephrase that',
         'I would be giving up', 'what I want now is']


def build():
    D.assert_no_key_is_longest(QUESTIONS, 'PHARMA')
    D.assert_bank_is_not_a_key(
        BANK, [a for rows, _ in GAPS for _, aa, _ in rows for a in aa])

    logo = D.logo_from(TPL)

    slides = (
        D.cover(logo, E['coverTitle'], E['coverSub'],
                [('Level', E['chipLevel']),
                 ('Focus', E['chipFocus']),
                 ('Count', E['chipCount'])])

        + "".join(D.teach(ek, E[ek], tk, E[tk],
                          [(hk, E[hk], body, nk, E[nk]) for hk, body, nk in cards],
                          folder=F, bg=bg)
                  for ek, tk, cards, bg in TEACH)

        + "".join(D.sort_slide(s['bins'], s['items'],
                               'sortEyebrow', E['sortEyebrow'],
                               s['title_key'], E[s['title_key']],
                               s['hint_key'], E[s['hint_key']], s['why'],
                               folder=F, bg=BG_OFFER if n else None)
                  for n, s in enumerate(SORTS))

        + "".join(D.gap(i + 1, len(GAPS), rows, BANK,
                        'gapEyebrow', E['gapEyebrow'],
                        'gapTitle', E['gapTitle'],
                        hint=E['gapHint'], hint_key='gapHint', why=why,
                        width=170)
                  for i, (rows, why) in enumerate(GAPS))

        + "".join(D.order(o['items'], 'ordEyebrow', E['ordEyebrow'],
                          o['title_key'], E[o['title_key']],
                          o['hint_key'], E[o['hint_key']], o['why'])
                  for o in ORDERS)

        + "".join(D.mc(i + 1, len(QUESTIONS), q,
                       'qEyebrow', E['qEyebrow'], 'qTitle', E['qTitle'],
                       explains=q['explains'])
                  for i, q in enumerate(QUESTIONS))

        + D.results('resNext', E['resNext'])

        + D.activate(E['actTitle'], E['actUse'], CHIPS,
                     E['actSpeakKind'], E['actSpeakBrief'],
                     [E['actSpeak%d' % n] for n in (1, 2, 3, 4)],
                     E['actWriteKind'], E['actWriteBrief'], E['actPlaceholder'],
                     folder=F, bg=BG_PANEL)
    )

    s = D.assemble(TPL, OUT, slides, PALETTE,
                   'The Pharma Sales Interview: Two Rounds in English (B2-C1)',
                   I, langs=('en', 'de'))

    # The chip has to say the number the checker reports, and the raw section
    # count is one higher — the template's authoring comment contains the
    # string '<section class="slide' too. Both the markup and the two
    # UI_I18N copies are rewritten, or the number changes the moment a
    # learner touches the switcher.
    n = s.count('<section class="slide') - 1
    s = s.replace('COUNT slides', '%d slides' % n)
    s = s.replace('COUNT Folien', '%d Folien' % n)

    # HOUSE-STYLE §5: a bright hero gets a heavier wash on THIS lesson and no
    # other, and the numbers are measured rather than chosen. At the template
    # default of 0.06/0.20 this coral hero rendered at
    #     mean_bg_luminance 0.1194, text vs brightest bg 4.12:1
    # against a target band of 0.025-0.08 and "comfortably above 7:1" — the
    # picture was washing the interior pages out rather than sitting behind
    # them. Re-measure with
    #     python3 lesson-template/bgmeasure.py <abs path to this deck>
    # if the hero is ever replaced; do not carry these values over to a
    # darker one.
    wash = ('  --wash-mid:  rgba(0,0,0,%s);\n  --wash-edge: rgba(0,0,0,%s);'
            % (WASH_MID, WASH_EDGE))
    old = '  --wash-mid:  rgba(0,0,0,0.06);\n  --wash-edge: rgba(0,0,0,0.20);'
    assert s.count(old) == 1, 'template wash block moved — re-find it'
    s = s.replace(old, wash, 1)

    open(OUT, 'w', encoding='utf-8').write(s)

    sort_pts = sum(len(x['items']) for x in SORTS)
    gap_pts = sum(len(r) for r, _ in GAPS)
    print('wrote %s — %d slides, %d scored (%d sort, %d gap, %d order, %d mc), '
          '%d bytes' % (OUT, n,
                        sort_pts + gap_pts + len(ORDERS) + len(QUESTIONS),
                        sort_pts, gap_pts, len(ORDERS), len(QUESTIONS), len(s)))


if __name__ == '__main__':
    build()
