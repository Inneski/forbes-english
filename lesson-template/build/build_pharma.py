"""The Pharma Sales Interview (B2-C1) — builder.

Written for a specific learner and it shows, which is the point. He leads
sales for a large pharmaceutical multinational, he is interviewing for a
pharmaceutical sales role at a much smaller Spanish company that also has a
German organisation, and he has two interviews in English inside a few weeks.
His own account of the problem: he communicates well but is out of practice
and sometimes has to search for the right word.

So the lesson does not teach interview vocabulary. Two things decide his
performance and neither is vocabulary:

* **The panel is Spanish.** English is their second language too. That
  inverts the usual advice — the Latinate register a British listener finds
  stiff (<em>demonstrate</em>, <em>sufficient</em>, <em>obtain</em>) is the
  register a Spanish listener decodes instantly, and the idiomatic phrasal
  verbs he has spent years acquiring (<em>pull it off</em>, <em>circle
  back</em>, <em>come up with</em>) are exactly what costs them. Almost no
  interview material says this, and it is the highest-yield thing in the
  deck. It is the whole of SORT_A.
* **Searching for a word is a public event.** The fix is not a bigger
  vocabulary in three weeks; it is four stall moves that make the search
  read as deliberate — frame the question, name the shape of the answer,
  flag the pause, and reach for the near word and correct upward. That is
  T2, and actSpeak3 is the task that measures whether he actually used one.

The rest is the structure that makes a record audible in somebody's second
language: Situation → Move → Number, and the results sentence
(<em>took the region from €4.2m to €6.1m in two years</em>) that carries a
start, an end and a time frame with nothing in it a panel has to take on
trust. SORT_B is the same test applied to self-description: every item in the
right-hand bin is true and none of it can be checked.

Shape: cover → 5 teach → 2 sort → 2 gap → 2 order → 8 mc → results →
activate. 21 slides, 34 scored points — the engine scores a sort per item and
a gap per input, not per slide, so the two sorts alone are worth 16.

Two things to know before changing anything here.

* **English lives in i18n_pharma.T['en'], not in this file.** The builder
  reads heads, notes, titles and briefs out of that dict. i18n_escalating
  documents nine keys whose English drifted from the shipped page, so a
  learner switching to German and back got a longer slide; reading both from
  one dict makes that impossible rather than merely unlikely. What *is* held
  here is the English being taught — stems, options, gap sentences, sort
  items, order chunks, explanations, chips and the quoted example lines in
  the teaching cards. Those never translate, so they have no key.
* **The hero is a stand-in.** PharmaInterview/hero.jpg was generated by
  make_pharma_hero.py because the five illustrations supplied with the
  request never reached the filesystem. Replacing it is a two-command job:
  drop the real JPEG at that path, re-run extract-palette.py on it, and paste
  the output over PALETTE. Do not hand-tune a channel.
"""
