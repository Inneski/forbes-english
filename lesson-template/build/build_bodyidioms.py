"""Elbow Grease (C1) — body idioms and verbs of contact. Part two of a pair.

`build_bodyparts.py` carries the thirty-six words of the same coursebook page
(Body and mind, unit 10, p.89) and its docstring explains why one lesson became
two: the page holds three exercises' worth of material, and HOUSE-STYLE §7 puts
the ceiling at about twenty-four slides. This deck is exercise 3 (the ten
idioms) and exercises 4-6 (the verbs), rebuilt as questions.

Where the content came from, and the three judgement calls in it:

  * **The idiom sentences are the old lesson's**, not the coursebook's. They
    were already original C1 rewrites when the scrolling version was built —
    *the CEO dug her heels in over relocating the headquarters* rather than
    the coursebook's *I tried to persuade Pete* — and they place each idiom in
    a register a C1 learner actually needs it in. All ten kept their meaning
    notes, which are now the gap explanations.

  * **Eighteen verbs, not seventeen or nineteen.** The coursebook lists
    seventeen; the old lesson had eighteen, having added *spit* and *rub* and
    dropped *pat*. *Pat* is restored — it is the ordinary word for what you do
    to a dog, and it pairs with *smack* to make the point that the same flat
    hand takes two verbs. *Rub* stays. *Spit* goes: it is the one verb on the
    list a learner will never need politely, and eighteen divides into three
    matching rounds of six where nineteen does not.

  * **The idioms are never glossed.** German turns *keep your chin up* into
    *Kopf hoch* — a different body part, which is the interesting fact and
    also the answer key if it is printed beside the gap. It belongs in the
    speaking task, and that is where it is.

Art: the four-hands plate is the hero and the verb divider; the speech-ribbon
plate carries the idiom stage; the wordless arm-and-hand plate sits behind the
verb questions; the two-profiles plate closes the deck. All are
`BodyParts/`, all are generated by `plates_bodyparts.py`, and the palette is
derived from the hero like any other.

    py lesson-template/build/build_bodyidioms.py
    node lesson-template/check-lesson.js forbes-english-body-idioms-c1.html
"""
