def build():
    logo = D.logo_from(TPL)
    D.assert_no_key_is_longest(QUESTIONS)
    for g in GAPS + [VERB_GAP]:
        D.assert_bank_is_not_a_key(g['bank'], [r[1][0] for r in g['rows']])

    def match_slide(pairs, key, eyebrow_key, bg):
        return D.match(pairs, eyebrow_key, E[eyebrow_key],
                       key + 'Title', E[key + 'Title'],
                       key + 'Hint', E[key + 'Hint'],
                       key + 'Why', folder=F, bg=bg)

    def gap_slide(i, total, g):
        return D.gap(i, total, g['rows'], g['bank'], 'gapEyebrow', E['gapEyebrow'],
                     g['title_key'], E[g['title_key']],
                     hint=E[g['hint_key']], hint_key=g['hint_key'],
                     width=165, folder=F, bg=g['bg'])

    slides = "".join(
        [D.cover(logo, E['coverTitle'], E['coverSub'],
                 [('Level', E['chipLevel']), ('Focus', E['chipFocus']),
                  ('Count', E['chipCount'])])]

        # ── stage one: the idioms ──
        + [D.teach('t1Eyebrow', E['t1Eyebrow'], 't1Title', E['t1Title'],
                   [(None, 'keep your <strong>chin</strong> up', 't1b1', E['t1b1'],
                     't1n1', E['t1n1']),
                    (None, 'a rule of <strong>thumb</strong>', 't1b2', E['t1b2'],
                     't1n2', E['t1n2']),
                    (None, '<strong>toe</strong> the line', 't1b3', E['t1b3'],
                     't1n3', E['t1n3'])],
                   folder=F, bg=BG_IDIOM)]
        + [D.divider('d1Title', E['d1Title'], 'd1Note', E['d1Note'],
                     folder=F, pic=PIC_IDIOM)]
        + [gap_slide(i + 1, len(GAPS) + 1, g) for i, g in enumerate(GAPS)]
        + [D.mc(i + 1, len(QUESTIONS), q, 'qEyebrow', E['qEyebrow'],
                'qTitle', E['qTitle'], folder=F, bg=q['bg'],
                ctx=q['ctx'], ctx_key=q['ctx_key'], stem_key=q['stem_key'])
           for i, q in enumerate(QUESTIONS[:3])]

        # ── stage two: the verbs ──
        + [D.divider('d2Title', E['d2Title'], 'd2Note', E['d2Note'],
                     folder=F, pic=HERO)]
        + [D.teach('t2Eyebrow', E['t2Eyebrow'], 't2Title', E['t2Title'],
                   [(None, 'slap &middot; smack &middot; shove', 't2b1', E['t2b1'],
                     't2n1', E['t2n1']),
                    (None, 'stroke &middot; pat &middot; rub &middot; hug', 't2b2', E['t2b2'],
                     't2n2', E['t2n2']),
                    (None, 'nod &middot; wink &middot; clap &middot; thumb', 't2b3', E['t2b3'],
                     't2n3', E['t2n3'])],
                   folder=F, bg=BG_VERB)]
        + [match_slide(pairs, key, 's2Eyebrow', 'limbs-plain.jpg')
           for pairs, key in MATCHES]
        + [D.sort_slide([E['sortBin1'], E['sortBin2'], E['sortBin3']], SORT_ITEMS,
                        'sortEyebrow', E['sortEyebrow'], 'sortTitle', E['sortTitle'],
                        'sortHint', E['sortHint'], 'sortWhy', folder=F,
                        bg=HERO,
                        bin_keys=['sortBin1', 'sortBin2', 'sortBin3'])]
        + [gap_slide(len(GAPS) + 1, len(GAPS) + 1, VERB_GAP)]
        + [D.mc(i + 4, len(QUESTIONS), q, 'qEyebrow', E['qEyebrow'],
                'qTitle', E['qTitle'], folder=F, bg=q['bg'],
                ctx=q['ctx'], ctx_key=q['ctx_key'], stem_key=q['stem_key'])
           for i, q in enumerate(QUESTIONS[3:])]

        + [D.results('resNext', E['resNext'], folder=F, bg=BG_TALK)]
        + [D.activate(E['actTitle'], E['actUse'], CHIPS,
                      E['actSpeakKind'], E['actSpeakBrief'], SPEAK,
                      E['actWriteKind'], E['actWriteBrief'], E['actPlaceholder'],
                      folder=F, bg=BG_TALK)]
    )

    s = D.assemble(TPL, OUT, slides, PALETTE,
                   'Elbow Grease: Body Idioms and Verbs of Contact (C1)',
                   I, langs=('en', 'de', 'es'))

    n = s.count('<section class="slide') - 1
    s = s.replace('NSLIDES', str(n))
    open(OUT, 'w', encoding='utf-8', newline='').write(s)

    gap_pts = sum(len(g['rows']) for g in GAPS) + len(VERB_GAP['rows'])
    pairs = sum(len(m) for m, _ in MATCHES)
    print('wrote %s - %d slides, %d scored (%d gap, %d match, %d sort, %d mc), '
          '%d bytes'
          % (OUT, n, gap_pts + pairs + len(SORT_ITEMS) + len(QUESTIONS),
             gap_pts, pairs, len(SORT_ITEMS), len(QUESTIONS), len(s)))


if __name__ == '__main__':
    build()
