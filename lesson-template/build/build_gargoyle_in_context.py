"""The Gargoyle House, Part 5: Words in Context (C1). House style 1. FREE.

Built 2026-11-15. Innes, after Part 4 (The Designer's Lexicon, definition ->
word): "I need one that puts words in context and you have to choose the
sentence with the right context for the chosen word." Then: "you dont need it
to be illustrated."

Same 100 words, same eight stages as Part 4. Each item names the word and
gives four sentences, set in the Gargoyle House story (Edith the designer,
Tom her junior, Bianca the client, Rex, Ashby Hall). One uses the word
correctly. The three wrong ones are wrong in the ways learners actually go
wrong, never by nonsense alone:
  - the look-alike's job: DIVISIVE where DECISIVE belongs, OVERLOOK for
    OVERSEE, CONFORM for CONFIRM, a PUPPETEER with strings
  - the wrong sense or the wrong scale: HEIRLOOM for a new purchase, KUDOS
    for a small thank-you note's money, TACKY paint that is bone dry
  - the wrong grammar or collocation: "very novice", "a kudo", "concede
    with", "look down him", RESTING ON a laurel
Every wrong sentence is wrong for one reason a teacher can name, and the
explanation names it.

No plates (Innes). hs1 puts the mirrored hero behind every slide without a
picture; on the question slides that is switched off (NO_WASH_CSS), because
four full sentences need the whole width and a plain ground.

Run from the repo root:  py lesson-template/build/build_gargoyle_in_context.py
"""
