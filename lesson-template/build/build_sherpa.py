def table_html(t, keyer):
    def cell(tag, r, ci, txt):
        key = keyer(r, ci)
        return '<%s%s>%s</%s>' % (tag, ' data-i18n="%s"' % key if key else '', txt, tag)
    head = ''.join(cell('th', 0, ci, x) for ci, x in enumerate(t['head']))
    rows = ''.join('<tr>%s</tr>' % ''.join(cell('td', ri, ci, x) for ci, x in enumerate(row))
                   for ri, row in enumerate(t['rows'], 1))
    return '<table class="sh-table"><thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (head, rows)


