"""Sherpa Tensing — the 25 camps, descents and clouds as 16:9 decks.

One builder for the whole family, driven by `sherpa/content/<slug>.json` (the
inventory `sherpa/extract.py` lifted out of the scrolling pages on 2026-09-22)
and `sherpa/i18n/<slug>.json` (the German and Spanish, the activation stage
and the cover line, authored per page).

    py lesson-template/build/build_sherpa.py            # every page
    py lesson-template/build/build_sherpa.py camp-03    # one
    py lesson-template/build/build_sherpa.py --list     # the slugs

What the scrolling pages were, and what changed in the conversion:

  * **Twenty-six scrolling reference pages, hand-maintained, patched by
    thirteen clone-and-patch builders** that sliced the live HTML of one camp
    to make the next (`build_c10.py` cut camp seven; `build_camp5.py` cut camp
    three; the descents cut whatever `build_c10` produced). Four camps had no
    builder at all. Every one of the 26 failed the six rules: no deck, no hero,
    no derived palette, no language switcher on 24 of them, and — the gap
    COURSES.md calls the largest in the catalogue — **no activation stage
    anywhere.** A learner could finish the entire tense system of English
    without producing a sentence.

  * **Nothing pedagogical is dropped.** Every rule card, form card, table,
    signal list, diagram, panel example and quiz item is here, in the same
    order the page taught it. The bespoke SVG diagrams — the best thing in the
    family — sit on the briefing slide and again on the interactive slide
    (HOUSE-STYLE §10: keep them). The click-to-reveal panels are shown open,
    side by side, so nothing waits behind a click that a projector cannot
    make.

  * **The eight passive_kit descents shipped with EMPTY interactive panels.**
    `passive_kit.build()` wrote `var exA = [\\n\\n];` into every page and then
    tried to fill it with a string replace that never matched, so two panel
    headings stood over nothing on the live site, on all eight, since they
    were built. The sentences were in the builders all along (`panelA` /
    `panelB`); the extractor recovers them and they are on the slides now.

  * **32 quiz items keyed the longest option** (HOUSE-STYLE §7, checked by
    `assert_no_key_is_longest` and by `check-lesson.js`). Twenty-six of them
    are on the three perfect-continuous camps, where the key is a five-word
    form against three-word distractors — a learner who has never opened the
    camp scores by picking the longest. Fixed per page in
    `sherpa/i18n/<slug>.json` under `quiz`, always by lengthening the
    distractors and never by touching the key.

  * **Grammar tokens now go in CAPS on the form cards** — `subject + WAS /
    WERE + verb-ING`, not `subject + was / were + -ing`. It is Innes's
    hardwired rule for learner-facing rules (see the Block Camp builders) and
    the family predated it. `caps_formula()` does it mechanically and only on
    a body that is a formula (one with ` + ` in it); prose bodies are left.

  * **The nine-language example translations are kept, not shown.** The old
    pages had an "Examples in: DE ES FR …" bar over `EX_TR`. The deck engine's
    gloss mechanism (`NARRATIVE_TR` + `.gloss[data-tr]`) shows a Translate
    button under an example in whatever language the deck is switched to —
    so German and Spanish work today, and the other seven light up the moment
    a later pass completes their `UI_I18N`. The data is in the page either
    way. Camps one and two's old eight-language UI strings are preserved in
    `content/<slug>.json` under `i18n` for that pass.

  * **The route map still works.** Each deck records its best score to
    `sherpa.progress.v1` in localStorage under the same id the scrolling page
    used, so the map's locks and counters read the decks exactly as they read
    the pages. The active/passive twin link and the way back to the map are
    on the results slide.

Artwork is `SherpaTensing/` — `hero-<slug>.jpg` per page and one texture per
section role and face (`bg-day-briefing.jpg`, `bg-night-climb.jpg`, …). The
set shipped first is interim, generated by `sherpa/interim_art.py`; the
commission that replaces it is `docs/ARTWORK-sherpa-tensing.md`, slot for
slot, same filenames.
"""
