def tune_svg(svg, suffix=None):
    """The page diagrams, made safe for the deck: DM Sans instead of the
    unloaded Inter, the click-to-reveal captions shown, and the old page's
    data-i18n hooks removed (the deck's I18N gate would demand a key for
    each, and they are English diagram labels).

    suffix: the hero diagram and the interactive one define the same
    gradient ids, and a gradient whose first definition sits on a hidden
    slide does not paint — the past block vanished from the interactive
    slide of the pilot. Every id in the second copy gets a suffix."""
    svg = svg.replace('Inter, sans-serif', "'DM Sans', sans-serif")
    if suffix:
        ids = re.findall(r'\sid="([^"]+)"', svg)
        for i in ids:
            svg = svg.replace('id="%s"' % i, 'id="%s-%s"' % (i, suffix))
            svg = svg.replace('url(#%s)' % i, 'url(#%s-%s)' % (i, suffix))
    svg = re.sub(r'\s+data-i18n="[^"]*"', '', svg)
    svg = re.sub(r'\s+tabindex="0"', '', svg)
    svg = re.sub(r'\s+role="button"', '', svg)
    svg = svg.replace('class="hero-diagram"', 'class="sh-svg"').replace('class="ring-hero-svg"', 'class="sh-svg"')
    if '<svg class="sh-svg"' not in svg:
        svg = svg.replace('<svg ', '<svg class="sh-svg" ', 1)
    return svg


