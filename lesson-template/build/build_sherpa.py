# ── grammar tokens in CAPS ────────────────────────────────────────────
AUX = {'am', 'is', 'are', 'was', 'were', 'be', 'been', 'being', 'have', 'has',
       'had', 'do', 'does', 'did', 'will', 'shall', 'not', 'going', 'to',
       'used', 'use', 'would', 'get', 'got', 'getting', "won't", "didn't",
       "haven't", "hasn't", "hadn't", "wasn't", "weren't", "isn't", "aren't",
       "don't", "doesn't", 'by'}
PHRASES = [('past participle', 'PAST PARTICIPLE'), ('base verb', 'BASE VERB'),
           ('past form', 'PAST FORM'), ('infinitive', 'INFINITIVE'),
           ('participle', 'PARTICIPLE'), ('verb-ing', 'verb-ING'),
           ('-ing', '-ING'), ('-ed', '-ED'), ('-es', '-ES')]


def caps_formula(body):
    """`subject + was / were + -ing`  ->  `subject + WAS / WERE + -ING`.

    Only a body with ` + ` in it is a formula; prose bodies are returned
    untouched. Tags are preserved: the pass runs over the text between them.
    Apostrophes may arrive as &#39; — normalised first so "didn&#39;t" is one
    token."""
    if ' + ' not in body:
        return body
    body = body.replace('&#39;', "'")
    parts = re.split(r'(<[^>]+>)', body)
    out = []
    for part in parts:
        if part.startswith('<'):
            out.append(part)
            continue
        for a, b in PHRASES:
            part = re.sub(r'(?<![\w-])' + re.escape(a) + r'(?![\w-])', b, part, flags=re.I)
        def up(m):
            w = m.group(0)
            return w.upper() if w.lower() in AUX else w
        part = re.sub(r"[A-Za-z']+", up, part)
        out.append(part)
    return ''.join(out).replace("'", '&#39;')


