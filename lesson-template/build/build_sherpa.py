ROUTE_MAP = os.path.join(ROOT, 'sherpa-tensing-route-map.html')
WHITE = (255, 255, 255)
_KEY = {}


def colour_key(c):
    """(colour, ink) for a page, read from the route map, which is the key.

    Each camp row there is `background:<colour>;color:<ink>`: the tense's
    colour and the ink the map itself sets on it (white on green, dark on
    yellow). A descent is the same tense turned around, so the map draws its
    dot in its twin camp's colour, and it takes that camp's ink. The clouds
    sit off the colour key, so they keep their own page's accent, with
    whichever of white or the page's ink reads better on it.

    Read from the map at build time rather than copied here, so a colour
    changed on the map reaches the decks on the next build and cannot drift.
    """
    if not _KEY:
        m = open(ROUTE_MAP, encoding='utf-8').read()
        _KEY['rows'] = {f: (bg, ink) for f, bg, ink in re.findall(
            r'href="(sherpa-tensing-[a-z0-9-]+\.html)" style="background:(#[0-9A-Fa-f]{6});color:(#[0-9A-Fa-f]{6})', m)}
        _KEY['dots'] = {f: col for col, f in re.findall(
            r'data-color="(#[0-9A-Fa-f]{6})" data-href="(sherpa-tensing-[a-z0-9-]+\.html)"', m)}
    hx = lambda v: tuple(int(v[i:i + 2], 16) for i in (1, 3, 5))
    rows, dots = _KEY['rows'], _KEY['dots']
    if c['kind'] == 'camp':
        bg, ink = rows[c['file']]
        return hx(bg), hx(ink)
    if c['kind'] == 'descent':
        bg, ink = rows[c['twin']]
        assert dots[c['file']].upper() == bg.upper(), \
            '%s: the route map draws it %s but its twin %s' % (c['slug'], dots[c['file']], bg)
        return hx(bg), hx(ink)
    P = _palette_tool()
    col, ink = hx(c['palette']['accent']), hx(c['palette']['ink'])
    return col, (WHITE if P.contrast_ratio(col, WHITE) >= P.contrast_ratio(col, ink) else ink)


# ── the inside field: one neutral texture set, dyed by the deck's colour ──
TEX_ROLES = ('briefing', 'building', 'fork', 'markers', 'stage', 'climb', 'view')
BG_OPACITY = 0.85        # the texture, multiplied onto --void
TEX_CONTRAST = 1.15      # the filter's contrast() on the texture
_FLOOR = []


def texture_floor():
    """The darkest 64px tile across the texture set, as the multiplier the
    field takes there: the worst ground a plate can sit on for dark ink."""
    if not _FLOOR:
        from PIL import Image
        lo = 1.0
        for r in TEX_ROLES:
            im = Image.open(os.path.join(ROOT, F, 'bg-day-%s.jpg' % r)).convert('L')
            tiles = im.resize((max(1, im.width // 64), max(1, im.height // 64)), Image.BOX)
            lo = min(lo, min(tiles.tobytes()) / 255.0)
        t = min(1.0, max(0.0, (lo - 0.5) * TEX_CONTRAST + 0.5))
        _FLOOR.append(1 - BG_OPACITY + BG_OPACITY * t)
    return _FLOOR[0]


def key_palette(c, hero_rel):
    """The deck tokens, from the tense's colour on the route map.

    NOT derived from the hero, which is the house rule everywhere else. The
    first build did derive them; on the placeholder covers that gave a muddy
    beige field with rust accents on four camps meant to be rose, maroon,
    violet and charcoal. Innes, 2026-09-23: "atrocious". The route map has
    been teaching learners these colours AS the tenses' colours, so this
    family is the exception because it is the one with a colour key. The
    picture follows the colour; it does not set it.

    The two faces invert each other. Innes: "active = green ink on white,
    passive = white ink on green".

      * camp / cloud: a white page faintly dyed with the colour, white boxes,
        and the colour as the ink, darkened until body text reaches 8:1.
      * descent: the colour IS the page, at full strength. The boxes carry
        the map's own ink for that colour: a deeper shade of it under white
        ink (green, maroon), a paler shade under dark ink (yellow, amber).

    The first pass walked every colour darker until white read on it, and
    camp six's yellow came out olive. Innes: "past continuous is supposed to
    be yellow". A light colour keeps its strength here and takes dark ink,
    as it does on the map, and on a white page it is shown as a highlighter
    behind the tense name rather than as ink that could not be read.

    Nothing is picked. Every token is the key colour, its ink, or one of
    those walked in lightness until its contrast row passes, and the build
    stops if any row still fails. The plate opacity is raised from the
    template's 0.68 when the worst ground the texture can make needs it.
    """
    P = _palette_tool()
    cr = P.contrast_ratio
    mix = lambda a, b, t: tuple(a[i] * t + b[i] * (1 - t) for i in range(3))
    lum = lambda col: P.rel_luminance(col)
    bad = tuple(int(c['palette']['bad'][i:i + 2], 16) for i in (1, 3, 5))

    def walk(col, bg, target, dl):
        for _ in range(80):
            if cr(col, bg) >= target:
                break
            col = P.shift(col, dl=dl)
        return col

    key, on = colour_key(c)
    passive = c['kind'] == 'descent'
    white_ink = on == WHITE
    PLATE = 0.68                         # the template's default opacity
    darkest = lambda col: tuple(v * texture_floor() for v in col)

    def apart(ab, ref, ground, dl):
        """Walk an accent away from the ink it must not be mistaken for,
        for as long as it still reads on the ground."""
        for _ in range(40):
            if cr(ab, ref) >= 1.45:
                break
            nxt = P.shift(ab, dl=dl)
            if cr(nxt, ground) < 4.5:
                break
            ab = nxt
        return ab

    # Every ink is walked against the ground it actually sits on: a plate at
    # the template's opacity over the worst tile the dyed texture makes. Dark
    # ink's worst tile is the darkest; light ink's is the bare colour, since
    # multiply only darkens.
    p = {'key': key, 'on-key': on}
    if not passive:
        # The tense name. A colour that reaches 3:1 on white with at most a
        # small walk is set as ink; one that would have to turn into another
        # colour to get there (yellow, amber) is a highlighter band behind
        # dark ink instead, so it is still seen at full strength. A colour
        # with no hue (camp thirteen's silver) is never a highlighter: a grey
        # band behind a word reads as a redaction, so it is walked as ink.
        ink3 = walk(key, WHITE, 3.0, -0.02)
        marked = (P.to_hls(key)[1] - P.to_hls(ink3)[1] > 0.08
                  and P.to_hls(key)[2] >= 0.12)
        # The ink cannot carry a highlighter colour, so its page does: a
        # stronger wash of the colour, or camp six would read as cream.
        p['void'] = mix(key, WHITE, 0.30 if marked else 0.10)
        p['surface'] = WHITE
        p['surface2'] = mix(key, WHITE, 0.16)
        g = mix(WHITE, darkest(p['void']), PLATE)
        p['text'] = walk(key, g, 8.0, -0.02)
        p['text-dim'] = walk(mix(p['text'], WHITE, 0.7), g, 5.0, -0.02)
        p['accent'] = walk(key, g, 4.5, -0.02)
        # A deep colour (camp ten's maroon) is past 8:1 already, so the
        # accent sits ON the ink: lift the accent first, then deepen the ink.
        ab = apart(p['accent'], p['text'], g, 0.02)
        for _ in range(40):
            if cr(ab, p['text']) >= 1.45:
                break
            p['text'] = P.shift(p['text'], dl=-0.02)
        p['accent-bright'] = ab
        p['border'] = walk(key, WHITE, 1.25, -0.02)
        p['contrast'] = walk(bad, g, 4.5, -0.02)
        if marked:
            p['title-ink'], p['title-mark'] = p['text'], key
        else:
            p['title-ink'], p['title-mark'] = ink3, None
        p['cover-card'], p['cover-ink'] = WHITE, p['text']
        if cr(key, on) >= 4.5:
            p['btn-bg'], p['btn-ink'] = key, on
        else:
            p['btn-bg'], p['btn-ink'] = p['accent'], WHITE
    else:
        p['void'] = key
        p['text'] = on
        if white_ink:
            # boxes a deeper shade of the colour: deep enough for white ink
            # through the see-through plate, and never so close to the field
            # that they disappear into it (descent ten's maroon)
            surf = key
            for _ in range(80):
                if cr(WHITE, mix(surf, key, PLATE)) >= 7.0 and cr(surf, key) >= 1.3:
                    break
                surf = P.shift(surf, dl=-0.02)
            p['surface'] = surf
            g = mix(surf, key, PLATE)
            p['text-dim'] = walk(mix(key, WHITE, 0.3), g, 4.5, 0.02)
            acc = walk(mix(key, WHITE, 0.45), g, 4.5, 0.02)
            ab = apart(acc, WHITE, g, -0.02)
            p['border'] = walk(mix(key, WHITE, 0.4), surf, 1.25, 0.02)
            p['contrast'] = walk(bad, g, 4.5, 0.02)
            p['cover-card'] = walk(key, WHITE, 4.5, -0.02)
            p['btn-bg'], p['btn-ink'] = WHITE, surf
        else:
            # boxes a paler shade of the colour, under the map's dark ink
            surf = mix(key, WHITE, 0.45)
            for _ in range(40):
                if cr(surf, key) >= 1.3:
                    break
                surf = P.shift(surf, dl=0.02)
            p['surface'] = surf
            g = mix(surf, darkest(key), PLATE)
            p['text-dim'] = walk(key, g, 5.0, -0.02)
            acc = walk(key, g, 4.5, -0.02)
            ab = apart(walk(key, g, 5.5, -0.02), on, g, 0.02)
            p['border'] = walk(key, surf, 1.25, -0.02)
            p['contrast'] = walk(bad, g, 4.5, -0.02)
            p['cover-card'] = key if cr(on, key) >= 4.5 else walk(key, on, 4.5, 0.02)
            p['btn-bg'] = on
            p['btn-ink'] = key if cr(key, on) >= 4.5 else surf
        p['surface2'] = mix(key, p['surface'], 0.5)
        p['accent'], p['accent-bright'] = acc, ab
        p['title-ink'], p['title-mark'], p['cover-ink'] = on, None, on
    p['accent-dim'] = key
    p['secondary'] = mix(key, WHITE, 0.35)

    # The plates are see-through, so the ground behind the glyphs is the
    # plate over the dyed texture, not the plate alone. The worst tile is
    # the brightest for light ink and the darkest for dark ink; multiply
    # can only darken, so the brightest is --void itself.
    light_ink = lum(p['text']) > 0.4
    field = p['void'] if light_ink else darkest(p['void'])
    inks = [('text', 4.5), ('text-dim', 4.5), ('accent', 4.5), ('accent-bright', 4.5)]
    plate = PLATE
    while plate < 0.97:
        ground = mix(p['surface'], field, plate)
        if all(cr(p[k], ground) >= mn for k, mn in inks):
            break
        plate = round(plate + 0.02, 2)
    ground = mix(p['surface'], field, plate)
    checks = [('%s on the plate over the texture' % k, p[k], ground, mn) for k, mn in inks] + [
        ('text on surface', p['text'], p['surface'], 4.5),
        ('text-dim on surface', p['text-dim'], p['surface'], 4.5),
        ('accent on surface', p['accent'], p['surface'], 4.5),
        ('accent-bright on surface', p['accent-bright'], p['surface'], 4.5),
        ('contrast on surface', p['contrast'], p['surface'], 4.5),
        ('border on surface', p['border'], p['surface'], 1.25),
        ('accent-bright vs text', p['accent-bright'], p['text'], 1.45),
        ('button label', p['btn-ink'], p['btn-bg'], 4.5),
        ('cover ink on the cover card', p['cover-ink'], p['cover-card'], 4.5),
        ('tense name on the cover card', p['title-ink'],
         p['title-mark'] or p['cover-card'], 3.0),
    ]
    failed = ['%s %.2f' % (l, cr(fg, bg)) for l, fg, bg, mn in checks if cr(fg, bg) < mn]
    if failed:
        raise SystemExit('colour key palette for %s fails: %s' % (c['slug'], ', '.join(failed)))
    order = ['void', 'surface', 'surface2', 'border', 'text', 'text-dim',
             'accent', 'accent-bright', 'accent-dim', 'secondary', 'contrast',
             'key', 'on-key', 'title-ink', 'cover-card', 'cover-ink', 'btn-bg', 'btn-ink']
    lines = ["  --hero: url('%s');" % hero_rel, '']
    for k in order:
        lines.append('  --%s : %s;' % (k.ljust(14), P.hex_of(p[k])))
    lines.append('  --%s : %s;' % ('title-mark'.ljust(14), P.hex_of(p['title-mark']) if p['title-mark'] else 'transparent'))
    if plate > PLATE:
        lines.append('  --plate         : %.2f;' % plate)
    return '\n'.join(lines), lum(p['text']) < 0.2


def quiet_side(hero_path):
    """'left' or 'right': the half of the picture the card should cover.

    A card in the middle hides exactly what a Sherpa picture is about (the
    ripples on the tarn, the tent on the ledge, the cairn), because the
    prompts put the subject low and off centre. So the card sits on the
    quieter half, measured the way check-negative-space.py measures a text
    column: edge energy in the band the card covers, left 55% against right
    55%. The subject stays in view whichever side it was painted on, and a
    replaced picture moves its card on the next build with no one deciding.
    """
    from PIL import Image, ImageFilter
    im = Image.open(hero_path).convert('L')
    im = im.resize((320, max(1, round(320 * im.height / im.width))))
    e = im.filter(ImageFilter.FIND_EDGES)
    w, h = e.size
    band = lambda x0, x1: sum(e.crop((x0, int(h * 0.18), x1, int(h * 0.86))).tobytes())
    return 'left' if band(0, int(w * 0.55)) <= band(int(w * 0.45), w) else 'right'


