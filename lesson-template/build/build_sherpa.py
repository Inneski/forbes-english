def is_forms_table(t):
    """A table whose every cell is an English form stays English."""
    return t['head'][0] in ('Subject', 'Base', 'Infinitive')


def en_strings(c):
    """Every learner-facing string that translates, keyed. The English of
    the target language (examples, forms, options, stems, word lists) is
    deliberately NOT here — HOUSE-STYLE §8."""
    T = {}
    h = c['hero']
    tense = re.sub(r'^.*?&middot;\s*', '', h['eyebrow'])
    T['coverTitle'] = h['h1']
    T['coverSub'] = ''                       # authored per page
    T['chipLevel'] = level_chip(c)
    T['chipFocus'] = tense[:1].upper() + tense[1:] + (' &middot; passive voice' if c['kind'] == 'descent' else '')
    T['chipCount'] = 'COUNT slides'
    T['briefEyebrow'] = h['eyebrow']
    T['briefTitle'] = tense[:1].upper() + tense[1:]
    T['brief'] = h['lede']
    for s in c['sections']:
        k = kid(s['id'])
        T[k + '_label'] = s['label'] or 'Interactive'
        T[k + '_title'] = s['title']
        if s.get('lead'):
            T[k + '_lead'] = s['lead']
        for i, card in enumerate(s.get('cards', []), 1):
            T['%s_c%dh' % (k, i)] = card['head']
            T['%s_c%db' % (k, i)] = caps_formula(card['body']) if s['id'] == 'form' else card['body']
        for i, ch in enumerate(s.get('charts', []), 1):
            if ch['head']:
                T['%s_ch%dh' % (k, i)] = ch['head']
            if ch['note']:
                T['%s_ch%dn' % (k, i)] = ch['note']
            if ch['example']:
                T['%s_ch%dex' % (k, i)] = ch['example']
            t = ch['table']
            if t and not is_forms_table(t):
                for ci, cell in enumerate(t['head']):
                    T['%s_ch%dt0c%d' % (k, i, ci)] = cell
                for ri, row in enumerate(t['rows'], 1):
                    for ci, cell in enumerate(row):
                        T['%s_ch%dt%dc%d' % (k, i, ri, ci)] = cell
        for i, sg in enumerate(s.get('signals', []), 1):
            T['%s_sg%dh' % (k, i)] = sg['head']
        dg = s.get('diagram')
        if dg:
            if dg['intro']:
                T[k + '_dintro'] = dg['intro']
            for i, p in enumerate(dg['panels'], 1):
                T['%s_p%dh' % (k, i)] = p['head']
            for i, b in enumerate(dg.get('bars', []), 1):
                T['%s_bar%dh' % (k, i)] = b['head']
                if b['body']:
                    T['%s_bar%db' % (k, i)] = b['body']
        if s.get('example'):
            T[k + '_ex'] = s['example']
        if s.get('freq') and s['freq'].get('rule'):
            T[k + '_rule'] = s['freq']['rule']
    for n, q in enumerate(c['quiz'], 1):
        if q.get('hint'):
            T['q%dctx' % n] = q['hint']
        T['q%dwhy' % n] = q['explain']
    r = c.get('results')
    if r:
        T['resPerfect'], T['resStrong'], T['resMid'] = r
        T['resLow'] = r[2]
    elif c.get('i18n'):
        o = c['i18n']['en']
        T['resPerfect'], T['resStrong'], T['resMid'] = o['msgPerfect'], o['msgStrong'], o['msgOk']
        T['resLow'] = o['msgOk']
    T['linkMap'] = '&larr; Back to the route map'
    T['linkTwin'] = ('Same tense, active voice &#8646;' if c['kind'] == 'descent'
                     else 'Same tense, passive voice &#8646;')
    T['eyeInteractive'] = 'Interactive'
    T['eyeQuiz'] = 'The climb'
    T['tQuiz'] = 'Practice'
    T['bankLabel'] = 'Word bank:'
    for k in ('actTitle', 'actUse', 'actSpeakBrief', 'actSpeak1', 'actSpeak2',
              'actSpeak3', 'actWriteKind', 'actWriteBrief', 'actPlaceholder'):
        T[k] = ''                            # authored per page
    return T


