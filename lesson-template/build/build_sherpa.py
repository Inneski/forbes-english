# ── i18n module shim for deck.assemble() ─────────────────────────────
class I18nModule:
    def __init__(self, T):
        self.T = T

    def render(self, code):
        d = dict(self.T[code])
        for k in LIFT:
            d[k] = CHROME[code][k]
        return '{\n' + ',\n'.join(
            '    %s: %s' % (k, d[k] if k in LIFT else json.dumps(d[k], ensure_ascii=False))
            for k in sorted(d)) + '\n  }'


STUB = dict(coverSub='Stub cover line', actTitle='Stub activation', actUse='Use these',
            actSpeakBrief='Stub', actSpeak1='Stub one', actSpeak2='Stub two', actSpeak3='Stub three',
            actWriteKind='Writing', actWriteBrief='Stub brief', actPlaceholder='Stub')


def load_i18n(slug, stub=False):
    p = os.path.join(I18N, slug + '.json')
    if not os.path.exists(p):
        if stub:
            # layout sweeps only: never reaches a shipped build, because the
            # shipped build asks for German and Spanish and this has neither
            return dict(en=dict(STUB), chips=['one', 'two', 'three', 'four'])
        raise SystemExit('%s: no sherpa/i18n/%s.json — the deck cannot ship without its '
                         'German, Spanish, cover line and activation stage' % (slug, slug))
    return json.load(open(p, encoding='utf-8'))


def build(slug, langs=LANGS):
    c = json.load(open(os.path.join(CONTENT, slug + '.json'), encoding='utf-8'))
    A = load_i18n(slug, stub=(langs == ('en',)))
    EN = en_strings(c)
    EN.update(A.get('en', {}))
    missing_en = [k for k, v in EN.items() if v == '']
    if missing_en:
        raise SystemExit('%s: i18n has no English for %s' % (slug, missing_en))
    T = {'en': EN}
    for code in langs[1:]:
        tr = dict(A.get(code, {}))
        gone = [k for k in EN if k not in tr]
        if gone:
            raise SystemExit('%s: %s is missing %d keys: %s' % (slug, code, len(gone), gone[:12]))
        tr = {k: tr[k] for k in EN}       # only keys English has
        T[code] = tr

    face = 'night' if c['kind'] == 'descent' else 'day'
    dark = c['kind'] == 'descent'
    hero = '%s/hero-%s.jpg' % (F, slug)
    bg = lambda role: 'bg-%s-%s.jpg' % (face, role)
    quiz_fix = A.get('quiz', {})
    chips = A.get('chips') or []
    assert 4 <= len(chips) <= 8, '%s: %d activation chips (want 4-8)' % (slug, len(chips))

    logo = D.logo_from(TPL)
    slides = D.cover(logo, EN['coverTitle'], EN['coverSub'],
                     [('Level', EN['chipLevel']), ('Focus', EN['chipFocus']), ('Count', 'COUNT slides')])
    slides += brief_slide(c, EN, bg('briefing'))

    for s in c['sections']:
        sid = s['id']
        role = role_of(sid)
        b = bg(role)
        if sid == 'rules':
            n_cards = len(chunk(s['cards'], 3))
            n_charts = len(s.get('charts', []))
            slides += ''.join(cards_slides(s, EN, b, 1, n_cards + n_charts))
            if n_charts:
                slides += ''.join(chart_slides(s, EN, b, n_cards + 1, n_cards + n_charts))
        elif sid == 'form':
            n_charts = len(s.get('charts', []))
            slides += ''.join(cards_slides(s, EN, b, 1, 1 + n_charts, per=4))
            if n_charts:
                slides += ''.join(chart_slides(s, EN, b, 2, 1 + n_charts))
        elif sid.startswith('vs-'):
            slides += ''.join(fork_slides(s, EN, b))
        elif sid == 'signals':
            slides += ''.join(signals_slide(s, EN, b))
        elif sid == 'freq-slider':
            slides += ''.join(freq_slide(s, EN, b))
        elif s.get('diagram'):
            slides += ''.join(stage_slides(s, EN, b))
        else:
            raise SystemExit('%s: section %s has no slide shape' % (slug, sid))

    slides += ''.join(mc_slides(c, EN, bg('climb'), quiz_fix))
    slides += results_slide(c, EN, bg('climb'))
    slides += D.activate(EN['actTitle'], EN['actUse'], chips, 'Speaking', EN['actSpeakBrief'],
                         [EN['actSpeak1'], EN['actSpeak2'], EN['actSpeak3']],
                         EN['actWriteKind'], EN['actWriteBrief'], EN['actPlaceholder'],
                         folder=F, bg=bg('view'))

    palette = derive_palette(hero, dark)
    title = '%s | Forbes English' % re.sub(r'\s*\|\s*Forbes English\s*$', '', c['title'])
    out = os.path.join(ROOT, c['file'])
    s = D.assemble(TPL, out, slides, palette, _html.escape(title, quote=False), I18nModule(T), langs=langs)
    s = s.replace('\n</style>', EXTRA_CSS + '</style>', 1)
    n = len(re.findall(r'<section class="slide[^>]*\bdata-type=', s))
    s = s.replace('COUNT slides', '%d slides' % n)
    for code in langs[1:]:
        s = s.replace(T[code]['chipCount'], T[code]['chipCount'].replace('COUNT', str(n)))
    i = s.index('   ENGINE ')
    j = s.rfind('<script>', 0, i)
    s = s[:j] + narrative_tr(c) + s[j:]
    s = s.replace('\n</body>', '\n' + tail_script(c) + '</body>', 1)
    open(out, 'w', encoding='utf-8', newline='').write(s)
    print('%s -> %s: %d slides, langs %s' % (slug, c['file'], n, '+'.join(langs)))
    return out


def slugs():
    return sorted(f[:-5] for f in os.listdir(CONTENT) if f.endswith('.json'))


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if '--list' in sys.argv:
        print('\n'.join(slugs()))
        sys.exit()
    langs = LANGS
    if '--en-only' in sys.argv:
        langs = ('en',)
        LENIENT = True
    for slug in (args or slugs()):
        build(slug, langs)
