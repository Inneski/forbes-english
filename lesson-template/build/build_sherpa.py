# ── the tail: progression for the route map, and the example glosses ──
def tail_script(c):
    twin = json.dumps(c['twin']) if c.get('twin') else 'null'
    return '''
<script>
// ── Sherpa Tensing progression: the route map reads this ──
(function(){
  var KEY = "sherpa.progress.v1", ID = %s, FACE = %s, TWIN = %s;
  function read(){ try { return JSON.parse(localStorage.getItem(KEY)) || {}; } catch (e) { return {}; } }
  function write(p){ try { localStorage.setItem(KEY, JSON.stringify(p)); } catch (e) {} }
  var val = document.getElementById("scoreVal"), max = document.getElementById("scoreMax");
  if (!val || !max) return;
  new MutationObserver(function(){
    var s = parseInt(val.textContent, 10), t = parseInt(max.textContent, 10);
    if (!(t > 0)) return;
    var p = read(), prev = p[ID] && p[ID].best || 0;
    p[ID] = { face: FACE, best: Math.max(prev, s), total: t };
    write(p);
  }).observe(val, { childList: true, characterData: true, subtree: true });
})();
</script>
''' % (json.dumps(c['sherpa_id']), json.dumps(c['face']), twin)


def narrative_tr(c):
    """EX_TR (nine languages, keyed by the old data-tr id) as the engine's
    NARRATIVE_TR, so an example's Translate button works in any language the
    deck is switched to."""
    if not c.get('ex_tr'):
        return ''
    out = {}
    for i, lang in enumerate(c['tr_order']):
        out[lang] = {tr: rows[i] for tr, rows in c['ex_tr'].items() if i < len(rows) and rows[i]}
    return '<script>\nconst NARRATIVE_TR = %s;\n</script>\n' % json.dumps(out, ensure_ascii=False)


