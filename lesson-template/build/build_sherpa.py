LENIENT = False     # --en-only sweeps report the longest-key items instead of stopping


def mc_slides(c, T, bg, overrides):
    out = []
    qs = c['quiz']
    total = len(qs)
    for n, q in enumerate(qs, 1):
        opts = list(q['options'])
        fix = overrides.get(str(n))
        if fix and fix.get('options'):
            assert q['correct'] in fix['options'], 'quiz %s Q%d: the key must survive the fix' % (c['slug'], n)
            opts = list(fix['options'])
        key = opts.index(q['correct'])
        # deal the key across the letters in the source: the engine shuffles
        # at runtime, and the checker reads the markup (KEYS gate)
        pos = (n - 1) % 4
        rest = [o for i, o in enumerate(opts) if i != key]
        dealt = rest[:pos] + [opts[key]] + rest[pos:]
        item = dict(stem=q['prompt'], options=dealt, correct=pos, why='q%dwhy' % n)
        try:
            D.assert_no_key_is_longest([item], '%s Q%d' % (c['slug'], n))
        except AssertionError as e:
            if not LENIENT:
                raise
            print('  ! ' + str(e))
        out.append(D.mc(n, total, item, 'eyeQuiz', T['eyeQuiz'], 'tQuiz', T['tQuiz'],
                        folder=F, bg=bg, ctx=q.get('hint') or None,
                        ctx_key='q%dctx' % n if q.get('hint') else None))
    return out


