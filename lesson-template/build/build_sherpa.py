def tune_svg(svg, suffix=None):
    """The page diagrams, made safe for the deck: DM Sans instead of the
    unloaded Inter, the click-to-reveal captions shown, and the old page's
    data-i18n hooks removed (the deck's I18N gate would demand a key for
    each, and they are English diagram labels).

    suffix: the hero diagram and the interactive one define the same
    gradient ids, and a gradient whose first definition sits on a hidden
    slide does not paint — the past block vanished from the interactive
    slide of the pilot. Every id in the second copy gets a suffix."""
    svg = svg.replace('Inter, sans-serif', "'DM Sans', sans-serif")
    if suffix:
        ids = re.findall(r'\sid="([^"]+)"', svg)
        for i in ids:
            svg = svg.replace('id="%s"' % i, 'id="%s-%s"' % (i, suffix))
            svg = svg.replace('url(#%s)' % i, 'url(#%s-%s)' % (i, suffix))
    svg = re.sub(r'\s+data-i18n="[^"]*"', '', svg)
    svg = re.sub(r'\s+tabindex="0"', '', svg)
    svg = re.sub(r'\s+role="button"', '', svg)
    svg = svg.replace('class="hero-diagram"', 'class="sh-svg"').replace('class="ring-hero-svg"', 'class="sh-svg"')
    if '<svg class="sh-svg"' not in svg:
        svg = svg.replace('<svg ', '<svg class="sh-svg" ', 1)
    return svg


# ── slide builders ────────────────────────────────────────────────────
def head_html(ek, e, tk, t, counter=None):
    cnt = ' &middot; %s' % counter if counter else ''
    return '''      <div class="slide-head"><div>
        <div class="eyebrow"><span data-i18n="%s">%s</span>%s</div>
        <h2 class="slide-title" data-i18n="%s">%s</h2>
      </div></div>''' % (ek, e, cnt, tk, t)


def section(body, bg, dtype='teach', extra=''):
    return '''
    <section class="slide" data-type="%s"%s%s>
%s
    </section>
''' % (dtype, D._bg(F, bg), extra, body)


def gloss_p(ex, tr, cls='prose dim sh-ex'):
    if not ex:
        return ''
    attr = ' data-tr="%d"' % tr if tr else ''
    g = ' gloss' if tr else ''
    return '\n            <p class="%s%s"%s>%s</p>' % (cls, g, attr, ex)


def card_html(hk, h, bk, b, ex=None, tr=None, body_cls='prose sh-body'):
    return '''<div class="card sh-card">
            <p class="prose"><strong data-i18n="%s">%s</strong></p>
            <p class="%s" data-i18n="%s">%s</p>%s
          </div>''' % (hk, h, body_cls, bk, b, gloss_p(ex, tr))


def cols_html(cards, grid):
    return '''      <div class="slide-body">
        <div class="cols" style="grid-template-columns:%s">
          %s
        </div>
      </div>''' % (grid, '\n          '.join(cards))


def chunk(items, size):
    out = []
    i = 0
    n = len(items)
    while i < n:
        take = size
        if n - i == 4 and size == 3:
            take = 2
        out.append(items[i:i + take])
        i += take
    return out


def cards_slides(s, T, bg, counter_from=1, total=None, per=3, ek=None, tk=None):
    k = kid(s['id'])
    ek = ek or k + '_label'
    tk = tk or k + '_title'
    cards = s['cards']
    groups = chunk(cards, per)
    total = total or len(groups)
    out = []
    for gi, g in enumerate(groups):
        htmls = []
        for i, card in enumerate(cards, 1):
            if card not in g:
                continue
            htmls.append(card_html('%s_c%dh' % (k, i), T['%s_c%dh' % (k, i)],
                                   '%s_c%db' % (k, i), T['%s_c%db' % (k, i)],
                                   card['ex'], card['tr']))
        n = counter_from + gi
        counter = '%d / %d' % (n, total) if total > 1 else None
        body = head_html(ek, T[ek], tk, T[tk], counter) + '\n' + cols_html(htmls, ' '.join(['1fr'] * len(g)))
        out.append(section(body, bg))
    return out


def table_html(t, keyer):
    def cell(tag, r, ci, txt):
        key = keyer(r, ci)
        return '<%s%s>%s</%s>' % (tag, ' data-i18n="%s"' % key if key else '', txt, tag)
    head = ''.join(cell('th', 0, ci, x) for ci, x in enumerate(t['head']))
    rows = ''.join('<tr>%s</tr>' % ''.join(cell('td', ri, ci, x) for ci, x in enumerate(row))
                   for ri, row in enumerate(t['rows'], 1))
    return '<table class="sh-table"><thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (head, rows)


def chart_slides(s, T, bg, counter_from, total, ek=None):
    """One slide per chart-wrap: heading, note, table, closing example."""
    k = kid(s['id'])
    ek = ek or k + '_label'
    out = []
    for i, ch in enumerate(s['charts'], 1):
        tk = '%s_ch%dh' % (k, i) if ch['head'] else k + '_title'
        counter = '%d / %d' % (counter_from + i - 1, total) if total > 1 else None
        parts = [head_html(ek, T[ek], tk, T[tk], counter), '      <div class="slide-body">']
        if ch['note']:
            parts.append('        <p class="prose dim sh-note" data-i18n="%s_ch%dn">%s</p>' % (k, i, T['%s_ch%dn' % (k, i)]))
        if ch['table']:
            t = ch['table']
            forms = is_forms_table(t)
            keyer = (lambda r, ci: None) if forms else (lambda r, ci, i=i: '%s_ch%dt%dc%d' % (k, i, r, ci))
            parts.append('        <div class="card sh-tcard">%s</div>' % table_html(t, keyer))
        if ch['example']:
            parts.append('        <p class="prose sh-example" data-i18n="%s_ch%dex">%s</p>' % (k, i, T['%s_ch%dex' % (k, i)]))
        parts.append('      </div>')
        out.append(section('\n'.join(parts), bg))
    return out


def fork_slides(s, T, bg):
    """The fork in the path: the table on one slide, its worked example and
    the cross-links on the next."""
    k = kid(s['id'])
    ch = s['charts'][0]
    ek, tk = k + '_label', k + '_title'
    out = []
    parts = [head_html(ek, T[ek], tk, T[tk]), '      <div class="slide-body">']
    if ch['note']:
        parts.append('        <p class="prose dim sh-note" data-i18n="%s_ch1n">%s</p>' % (k, T[k + '_ch1n']))
    parts.append('        <div class="card sh-tcard">%s</div>' % table_html(ch['table'], lambda r, ci: '%s_ch1t%dc%d' % (k, r, ci)))
    parts.append('      </div>')
    out.append(section('\n'.join(parts), bg))
    if ch['example'] or s.get('links'):
        parts = [head_html(ek, T[ek], tk, T[tk]), '      <div class="slide-body">']
        if ch['example']:
            parts.append('        <div class="card"><p class="prose sh-pull" data-i18n="%s_ch1ex">%s</p></div>' % (k, T[k + '_ch1ex']))
        if s.get('links'):
            links = ' &nbsp;&middot;&nbsp; '.join('<a href="%s">%s</a>' % (href, txt) for href, txt in s['links'])
            parts.append('        <p class="prose dim sh-links">%s</p>' % links)
        parts.append('      </div>')
        out.append(section('\n'.join(parts), bg))
    return out


def signals_slide(s, T, bg):
    k = kid(s['id'])
    ek, tk = k + '_label', k + '_title'
    parts = [head_html(ek, T[ek], tk, T[tk]), '      <div class="slide-body">']
    for i, ch in enumerate(s.get('charts', []), 1):
        # camp four: a note with no table, above the boxes
        if ch['note'] and not ch['table']:
            parts.append('        <p class="prose dim sh-note"><strong data-i18n="%s_ch%dh">%s</strong> &mdash; <span data-i18n="%s_ch%dn">%s</span></p>'
                         % (k, i, T['%s_ch%dh' % (k, i)], k, i, T['%s_ch%dn' % (k, i)]))
    boxes = []
    for i, sg in enumerate(s['signals'], 1):
        items = ''.join('<li>%s</li>' % x for x in sg['items'])
        boxes.append('<div class="card sh-card"><p class="prose"><strong data-i18n="%s_sg%dh">%s</strong></p><ul class="sh-list">%s</ul></div>'
                     % (k, i, T['%s_sg%dh' % (k, i)], items))
    parts.append('        <div class="cols" style="grid-template-columns:%s">\n          %s\n        </div>'
                 % (' '.join(['1fr'] * len(boxes)), '\n          '.join(boxes)))
    if s.get('example'):
        parts.append('        <p class="prose dim sh-after" data-i18n="%s_ex">%s</p>' % (k, T[k + '_ex']))
    parts.append('      </div>')
    return [section('\n'.join(parts), bg)]


def stage_slides(s, T, bg):
    """The interactive diagram: the picture with its explanation, then what
    the click-to-reveal panels held, shown open."""
    k = kid(s['id'])
    dg = s['diagram']
    ek, tk = k + '_label', k + '_title'
    out = []
    n_after = (1 if dg['panels'] else 0) + len(chunk(dg.get('bars', []), 3)) + (1 if s.get('cards') else 0)
    total = 1 + n_after
    counter = lambda n: '%d / %d' % (n, total) if total > 1 else None
    parts = [head_html(ek, T[ek], tk, T[tk], counter(1)), '      <div class="slide-body sh-stage">']
    if dg['intro']:
        parts.append('        <p class="prose dim sh-note" data-i18n="%s_dintro">%s</p>' % (k, T[k + '_dintro']))
    # a long introduction takes the room from the picture: 130 words ran the
    # camp eight slide 41px past the canvas at the full 760px
    nwords = len(re.sub(r'<[^>]+>', '', dg['intro'] or '').split())
    maxw = 760 if nwords <= 50 else 700 if nwords <= 80 else 600
    parts.append('        <div class="card sh-svgcard" style="max-width:%dpx">%s</div>' % (maxw, tune_svg(dg['svg'], 'st')))
    parts.append('      </div>')
    out.append(section('\n'.join(parts), bg))
    n = 2
    if dg['panels']:
        boxes = []
        for i, p in enumerate(dg['panels'], 1):
            items = ''.join('<li>%s</li>' % x for x in p['items'])
            boxes.append('<div class="card sh-card"><p class="prose"><strong data-i18n="%s_p%dh">%s</strong></p><ul class="sh-list sh-panel">%s</ul></div>'
                         % (k, i, T['%s_p%dh' % (k, i)], items))
        body = head_html(ek, T[ek], tk, T[tk], counter(n)) + '\n' + cols_html(boxes, ' '.join(['1fr'] * len(boxes)))
        out.append(section(body, bg))
        n += 1
    for g in chunk(dg.get('bars', []), 3):
        boxes = []
        for i, b in enumerate(dg['bars'], 1):
            if b not in g:
                continue
            exs = ''.join('<li>%s</li>' % x for x in b['examples'])
            boxes.append('<div class="card sh-card"><p class="prose"><strong data-i18n="%s_bar%dh">%s</strong></p><p class="prose sh-body" data-i18n="%s_bar%db">%s</p><ul class="sh-list sh-panel">%s</ul></div>'
                         % (k, i, T['%s_bar%dh' % (k, i)], k, i, T.get('%s_bar%db' % (k, i), ''), exs))
        body = head_html(ek, T[ek], tk, T[tk], counter(n)) + '\n' + cols_html(boxes, ' '.join(['1fr'] * len(boxes)))
        out.append(section(body, bg))
        n += 1
    if s.get('cards'):
        htmls = [card_html('%s_c%dh' % (k, i), T['%s_c%dh' % (k, i)], '%s_c%db' % (k, i), T['%s_c%db' % (k, i)], card['ex'], card['tr'])
                 for i, card in enumerate(s['cards'], 1)]
        body = head_html(ek, T[ek], tk, T[tk], counter(n)) + '\n' + cols_html(htmls, ' '.join(['1fr'] * len(htmls)))
        if s.get('example'):
            body = body.replace('      </div>\n', '        <p class="prose dim sh-after" data-i18n="%s_ex">%s</p>\n      </div>\n' % (k, T[k + '_ex']), 1) if False else body
            body = body[:body.rstrip().rfind('</div>')] + '  <p class="prose dim sh-after" data-i18n="%s_ex">%s</p>\n      </div>' % (k, T[k + '_ex'])
        out.append(section(body, bg))
    return out


