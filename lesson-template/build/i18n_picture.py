def render(code):
    """Emit one language as a JS object literal."""
    d = dict(T[code])
    for k in LIFT:
        d[k] = CHROME[code][k]          # already a JS literal
    parts = []
    for k in sorted(d):
        v = d[k]
        if k in LIFT:
            parts.append('    %s: %s' % (k, v))
        else:
            parts.append('    %s: %s' % (k, json.dumps(v, ensure_ascii=False)))
    return '{\n' + ',\n'.join(parts) + '\n  }'


