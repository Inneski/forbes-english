def esc(s):
    return hub.esc(s)


def plain(s):
    return html.unescape(re.sub(r'<[^>]+>', '', s))


def and_list(xs):
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' and ' + xs[-1]


def load(rows):
    """Every route, in build_ielts_hub.ROUTES order, each lesson annotated
    from the catalogue. Stops the build on anything it cannot render."""
    from ielts_routes import ROUTES as DATA
    data = {d['hub']: d for d in DATA}
    order = [r['hub'] for r in hub.ROUTES]
    if sorted(data) != sorted(order):
        sys.exit('! tools/ielts_routes.py has %s, build_ielts_hub.ROUTES has %s: they must list '
                 'the same route pages' % (sorted(data), sorted(order)))
    cat = {x['file']: x for x in rows}
    out, missing = [], []
    for i, meta in enumerate(hub.ROUTES):
        d = data[meta['hub']]
        r = dict(meta, **d, n=i + 1)
        r['tracks'] = [t for t in d['tracks'] if t['lessons']]
        if not r['tracks']:
            sys.exit('! %s has no lessons in tools/ielts_routes.py' % r['hub'])
        for ref in r.get('reference') or []:
            for l in ref['lessons']:
                if l['file'] != 'ielts-question-bank.html':
                    sys.exit('! %s: reference card %s has no design yet' % (r['hub'], l['file']))
        n = 0
        for t in r['tracks']:
            for l in t['lessons']:
                n += 1
                row = cat.get(l['file'])
                if row is None:
                    missing.append(l['file'])
                if not os.path.exists(os.path.join(ROOT, l['file'])):
                    sys.exit('! %s lists %s, which does not exist' % (d['hub'], l['file']))
                l.update(n=n, short=hub.short_title(l['title']),
                         free=bool(row) and row.get('access') != 'pro',
                         level=(row or {}).get('level') or '',
                         full=seo.clean(row['title'] if row else l['title']),
                         produces=hub.produces(l['file']))
        r['stops'] = [l for t in r['tracks'] for l in t['lessons']]
        free = [l for l in r['stops'] if l['free']]
        r['first'] = free[0] if free else r['stops'][0]
        if free and free[0] is not r['stops'][0]:
            print('  ! %s: the first lesson is not free; the start button goes to lesson %d'
                  % (r['hub'], free[0]['n']))
        out.append(r)
    for f in missing:
        print('  ! %s is on a route but not in the catalogue; shown as subscriber-only' % f)
    return out


def fill(text, r):
    """The placeholders a lede or a teaching note may use."""
    count = len(r['stops'])
    silent = [l['short'] for l in r['stops'] if not l['produces']]
    if silent:
        s = ('All but %s &mdash; %s &mdash; end with writing you actually produce rather than recognise.'
             % (hub.words(len(silent)), and_list(silent)) if len(silent) < count
             else 'None of them yet ends with writing you produce yourself.')
    else:
        s = 'Every one ends with writing you actually produce rather than recognise.'
    below = [l for l in r['stops'] if l['level'][:1] in ('A', 'B')]     # starts below C1
    levels = ('The whole set is C1' if not below else 'Everything is C1 except %s' % and_list(
        ['<em>%s</em>, which starts at %s' % (l['short'], l['level'][:2]) for l in below]))
    return (text.replace('{Count}', hub.words(count).capitalize())
                .replace('{count}', hub.words(count)).replace('{silent}', s)
                .replace('{levels}', levels))


def stop_html(l, start):
    tags = []
    if l['free']:
        tags.append('<span class="ih-pill">Free</span>')
    if start:
        tags.append('<span class="ir-tag ir-tag-start">Start here</span>')
    if l['level']:
        tags.append('<span class="ir-tag">%s</span>' % esc(l['level']))
    tags += ['<span class="ir-tag">%s</span>' % t for t in l['tags']]
    return ('        <li class="ir-stop%s">\n'
            '          <span class="ih-dot" aria-hidden="true">%d</span>\n'
            '          <div>\n'
            '            <h3 class="ir-stop-t"><a href="%s">%s</a></h3>\n'
            '            <p class="ir-stop-d">%s</p>\n'
            '            <p class="ir-tags">%s</p>\n'
            '          </div>\n'
            '          <span class="ir-go" aria-hidden="true">Open &rarr;</span>\n'
            '        </li>'
            % (' ih-free' if l['free'] else '', l['n'], seo.quote(l['file']), l['short'], l['desc'],
               '<span class="ih-vh">, </span>'.join(tags)))


