def chrome():
    """The first stylesheet, the font links and the top band, from ielts.html
    — the same lift build_hubs.py does — so the nav cannot drift again. The
    IELTS tab is the current section here, not the current page."""
    src = open(os.path.join(ROOT, 'ielts.html'), encoding='utf-8').read()
    style = re.search(r'<style>.*?</style>', src, re.S).group(0)
    fonts = '\n'.join(re.findall(r'<link[^>]+(?:preconnect|fonts\.googleapis)[^>]*>', src))
    nav = re.search(r'<nav class="topband">.*?</nav>', src, re.S).group(0)
    nav = nav.replace(' aria-current="page"', ' aria-current="true"')
    return style, fonts, nav


