def _owned(src):
    """The page minus the parts other tools own: the SEO fence and <title>
    (tools/seo.py) and the marker line itself."""
    src = re.sub(re.escape(seo.START) + '.*?' + re.escape(seo.END), '', src, flags=re.S)
    src = re.sub(r'<title>.*?</title>', '', src, flags=re.S)
    return re.sub(MARK_RX, '', src)


def _sha(src):
    return hashlib.sha1(_owned(src).encode('utf-8')).hexdigest()[:12]


def build(rows=None, images=None, check=False, force=False):
    """Build the five route pages. All or nothing: if any page was edited by
    hand (or has lost its marker) and force is off, write nothing at all and
    return it in `refused`. Returns (stale, refused)."""
    hub.STATE.update(check=check, missing=[])
    if rows is None:
        rows, source = seo.lessons(write_cache=not check)
        print('  lessons: %d (from %s)' % (len(rows), source))
    if images is None:
        images = seo.lesson_images()
    routes = load(rows)
    out, refused = [], []
    for r in routes:
        path = os.path.join(ROOT, r['hub'])
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        m = re.search(MARK_RX, old)
        if old and not force:
            if m and m.group(1) != _sha(old):
                refused.append(r['hub'])
                print('  ! %s was edited by hand since it was generated. Move the change into '
                      'tools/ielts_routes.py, or re-run with --force to discard it.' % r['hub'])
                continue
            if not m:
                refused.append(r['hub'])
                print('  ! %s has no generator marker, so it may hold hand-written content. '
                      'Re-run with --force to replace it.' % r['hub'])
                continue
        out.append((r, path, old))
    if refused and not force:
        print('  ! nothing written: the six IELTS pages are built together or not at all.')
        return True, refused
    series = hub.mosaic(routes, images)
    stale = []
    for r, path, old in out:
        seo_m = re.search(re.escape(seo.START) + '.*?' + re.escape(seo.END), old, re.S)
        title_m = re.search(r'<title>.*?</title>', old, re.S)
        new = page(r, routes, series,
                   seo_m.group(0) if seo_m else '%s\n%s' % (seo.START, seo.END),
                   title_m.group(0)[7:-8] if title_m else 'IELTS %s | Forbes English' % r['name'])
        new = new.replace('%MARK%', MARK % _sha(new.replace('%MARK%\n', '')), 1)
        if new != old:
            stale.append(r['hub'])
            if not check:
                open(path, 'w', encoding='utf-8', newline='\n').write(new)
        print('  %-22s %2d lessons, %d free, %s%s' % (
            r['hub'], len(r['stops']), sum(1 for l in r['stops'] if l['free']),
            plain(hub.level_span([l['level'] for l in r['stops']])) or '-',
            (' — STALE' if check else ' — rewritten') if r['hub'] in stale else ' — unchanged'))
    for m in hub.STATE['missing']:
        print('  ! %s would be written' % m)
    return bool(stale) or bool(hub.STATE['missing']), refused


def build_all(rows=None, images=None, check=False, force=False):
    """The five route pages, then the landing page, which links into them
    and shares their pictures. The landing page is not touched if a route
    page was refused. Returns (stale, refused)."""
    if rows is None:
        rows, source = seo.lessons(write_cache=not check)
        print('  lessons: %d (from %s)' % (len(rows), source))
    if images is None:
        images = seo.lesson_images()
    stale, refused = build(rows, images, check=check, force=force)
    if refused:
        return stale, refused
    return hub.build(rows, images, check=check) or stale, refused


if __name__ == '__main__':
    check = '--check' in sys.argv
    failures = hub.contrast_report()
    stale, refused = build_all(check=check, force='--force' in sys.argv)
    if refused:
        sys.exit(2)
    if failures:
        sys.exit('! %d contrast pair(s) fail' % failures)
    if check and stale:
        sys.exit(1)
