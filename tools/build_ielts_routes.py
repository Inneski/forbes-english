"""Build the five IELTS route pages from `tools/ielts_routes.py`.

    python3 tools/build_ielts_routes.py            # all six IELTS pages; then tools/seo.py
    python3 tools/build_ielts_routes.py --check    # exit 1 if any of the six is stale
    python3 tools/build_ielts_routes.py --force    # overwrite hand edits

`tools/build_hubs.py` runs the same thing (`build_all`), and so does
`tools/build_ielts_hub.py` from the command line: the route pages and the
landing page share their web-sized pictures in `ielts-hub/`, and a picture
that changes is re-cut and its old copy deleted, so they are always built
together or a page is left pointing at a deleted file.

WHY. The route pages were hand-written in the site's older IELTS design,
so the landing page (`ielts.html`, redesigned 2026-09-25) led into five
pages that looked like a different site, with a nav that had lost the
Level Check link and Free/Pro tags typed by hand. They now share the
landing page's palette, type, buttons and stop list — the `ih-` block from
`build_ielts_hub.py`, carried whole — and add only what a route page needs,
in an `ir-` block below it. The landing page is a chooser; a route page is
the full, described list for one paper, so it keeps every description and
teaching note and does not repeat the test-to-scale or the symptom list.

WHAT IS COMPUTED. Free and level come from the catalogue; counts, the
level span, the start button, "Start here", the free/Pro line and
Writing's "all but two end with writing you produce" are counted, never
typed. Lesson titles lose their "IELTS Academic Writing:" prefix here as on
the landing page (`build_ielts_hub.short_title`). Route order, number, name
and colour family come from `build_ielts_hub.ROUTES`; everything else about
a route from `tools/ielts_routes.py`. The picture is the same web-sized copy
the landing page uses (`ielts-hub/route-*.jpg`), cropped by `hero_pos`.

HAND EDITS ARE REFUSED. Each page carries the hash of what this builder
wrote. If a page has changed since (anything but the SEO fence and the
<title>, which `tools/seo.py` owns), or exists without the marker, nothing
is written — not that page, not the others, not the landing page — and the
run says which page and exits 2. Move the edit into `tools/ielts_routes.py`,
or run with --force if it is meant to go.
"""
