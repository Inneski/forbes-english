# -*- coding: utf-8 -*-
"""The stand-in shopping list: every picture a live deck is still showing a
stand-in for, with the brief for the real one.

    py tools/standins.py            # rewrite docs/ARTWORK-standins.md
    py tools/standins.py --check    # print the count, write nothing

Measured, not maintained: it reads every root .html for references to
<folder>/standin-<slot>.png (or .jpg) and looks each slot's brief up in
<folder>/standins.json, which tools/make_standin.py writes when a builder
asks for a stand-in. A slot drops off the list the moment its builder is
re-run with the real plate on disk (deck.plate() prefers it).

Innes, 2026-11-06: "use stand in graphics to be replaced in shopping list".
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'ARTWORK-standins.md')

# The house stem (docs/ARTWORK-revamp-shopping-list.md, "The style, stated
# once"), unchanged except that every house style 2 picture sits in the
# CENTRE: the picture zone is about a third of the slide wide and crops a
# 16:9 plate to its middle, and the same file also fills a divider whole.
STEM = ('flat vector illustration, cel-shaded, solid flat colour, minimalist, '
        'Noma Bar style, one idea in negative space, wide landscape, {colours}, '
        'bright and airy, plain pale background, no text, no letters, no logos, '
        'no signage, no faces, subject contained in the centre third of the frame '
        'with empty flat ground either side --ar 16:9 --style raw --no '
        'photorealistic, gradient, texture, grain, depth of field, perspective')

COLOURS = {
    'warm': 'mustard yellow, terracotta, teal and navy on warm greige',
    'cool': 'cornflower blue, coral and sunflower yellow on pale blue',
    'rose': 'cream and dusty pink and coral with slate-blue and black silhouettes',
    'sage': 'sage green, ochre and rust on pale mint',
    'slate': 'slate blue, warm salmon and sand on pale grey',
}


def scan():
    rows = {}
    for page in sorted(glob.glob(os.path.join(ROOT, '*.html'))):
        s = open(page, encoding='utf-8', errors='replace').read()
        refs = sorted(set(re.findall(r'([A-Za-z0-9_\-./ ]+?)/standin-([a-z0-9\-]+)\.(?:png|jpg)', s)))
        refs = [(d.split('"')[-1].split("'")[-1].split('(')[-1].strip(), slot) for d, slot in refs]
        if refs:
            rows[os.path.basename(page)] = sorted(set(refs))
    return rows


def main():
    rows = scan()
    n = sum(len(v) for v in rows.values())
    if '--check' in sys.argv:
        print('%d stand-ins on %d pages' % (n, len(rows)))
        return
    out = ['# Stand-in shopping list — pictures to order for house style 2 decks', '',
           'Generated by `py tools/standins.py` from the pages themselves; do not edit by',
           'hand. Every deck below is LIVE on a flat stand-in figure for each slot listed.',
           'Innes, 2026-11-06: *"use stand in graphics to be replaced in shopping list"*.', '',
           '**To replace one:** render the prompt, drop the files in',
           '`incoming/<folder>/`, then `/publish` (it runs `tools/prep-artwork.py --into',
           '<folder> --names <slot>,…`). Re-run the deck\'s builder: `deck.plate()` takes',
           'the real `<slot>.jpg` over `standin-<slot>.png` automatically, and this list',
           'drops the slot on its next run. Re-derive the palette from the real hero',
           '(`extract-palette.py <folder>/hero.jpg --paper`) when the hero is replaced.', '',
           '**%d pictures on %d decks.**' % (n, len(rows)), '']
    for page, refs in rows.items():
        out.append('## `%s`' % page)
        out.append('')
        out.append('| folder | slot | brief | Midjourney prompt |')
        out.append('|---|---|---|---|')
        for folder, slot in refs:
            side = os.path.join(ROOT, folder, 'standins.json')
            rec = json.load(open(side, encoding='utf-8')).get(slot, {}) if os.path.exists(side) else {}
            brief = rec.get('brief', '*(no brief recorded)*')
            colours = COLOURS.get(rec.get('scheme', 'warm'), COLOURS['warm'])
            prompt = '%s, %s' % (brief, STEM.format(colours=colours))
            out.append('| `%s/` | `%s` | %s | `%s` |' % (folder, slot, brief, prompt))
        out.append('')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print('%s: %d stand-ins on %d pages' % (os.path.relpath(OUT, ROOT), n, len(rows)))


if __name__ == '__main__':
    main()
